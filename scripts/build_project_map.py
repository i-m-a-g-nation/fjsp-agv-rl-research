"""Build docs/project_map.html: docs/overview.md rendered in the browser, Mermaid diagrams included.

The page embeds the Markdown text and renders it client-side (marked + mermaid from jsDelivr, so it
needs an internet connection). Rerun after editing docs/overview.md:

    python scripts/build_project_map.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'docs' / 'overview.md'
TARGET = ROOT / 'docs' / 'project_map.html'

TEMPLATE = """<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>项目全景</title>
<!-- Generated by scripts/build_project_map.py from docs/overview.md; edit the Markdown, not this file. -->
<style>
  :root { --text: #1f2328; --muted: #59636e; --border: #d1d9e0; --code: #f6f8fa; --link: #0969da; --bg: #ffffff; }
  @media (prefers-color-scheme: dark) {
    :root { --text: #e6edf3; --muted: #9198a1; --border: #3d444d; --code: #151b23; --link: #4493f8; --bg: #0d1117; }
  }
  body { margin: 0; background: var(--bg); color: var(--text);
         font: 16px/1.65 -apple-system, "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif; }
  main { max-width: 1080px; margin: 0 auto; padding: 24px 16px 64px; }
  h1, h2, h3 { line-height: 1.3; } h2 { border-bottom: 1px solid var(--border); padding-bottom: .3em; margin-top: 2em; }
  a { color: var(--link); } blockquote { margin: 0; padding: 0 1em; color: var(--muted); border-left: 4px solid var(--border); }
  table { border-collapse: collapse; display: block; overflow-x: auto; margin: 1em 0; }
  th, td { border: 1px solid var(--border); padding: 6px 12px; vertical-align: top; }
  code { background: var(--code); padding: .1em .35em; border-radius: 4px; font-size: 90%; }
  pre { background: var(--code); padding: 12px; overflow-x: auto; border-radius: 6px; }
  .mermaid { background: #ffffff; border: 1px solid var(--border); border-radius: 8px; padding: 12px; margin: 1em 0;
             overflow-x: auto; text-align: center; }
</style>
</head>
<body>
<main id="content">正在加载……（需要联网加载 marked 与 mermaid）</main>
<script src="https://cdn.jsdelivr.net/npm/marked@12.0.2/marked.min.js"></script>
<script src="https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"></script>
<script>
const SOURCE = __SOURCE__;
const renderer = new marked.Renderer();
const plainCode = renderer.code.bind(renderer);
renderer.code = (code, lang, escaped) => {
  if (lang === 'mermaid') {
    const div = document.createElement('div');
    div.textContent = code;
    return '<pre class="mermaid">' + div.innerHTML + '</pre>';
  }
  return plainCode(code, lang, escaped);
};
document.getElementById('content').innerHTML = marked.parse(SOURCE, { renderer });
mermaid.initialize({ startOnLoad: false, theme: 'default', securityLevel: 'strict', flowchart: { htmlLabels: true } });
mermaid.run({ querySelector: '.mermaid' });
</script>
</body>
</html>
"""


def main() -> None:
    text = SOURCE.read_text(encoding='utf-8')
    page = TEMPLATE.replace('__SOURCE__', json.dumps(text, ensure_ascii=False).replace('</', '<\\/'))
    TARGET.write_text(page, encoding='utf-8', newline='\n')
    print(f'wrote {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
